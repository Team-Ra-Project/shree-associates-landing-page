function validateForm() {
  const t = translations[currentLang];
  let valid = true;
  const name = document.getElementById('fullName');
  const mobile = document.getElementById('mobile');
  const society = document.getElementById('societyName');
  const location = document.getElementById('location');
  const service = document.getElementById('service');
  document.querySelectorAll('.error-msg').forEach(e => e.textContent = '');
  document.querySelectorAll('.form-group input, .form-group select').forEach(el => el.classList.remove('error'));
  if (!name.value.trim()) { document.getElementById('nameError').textContent = t.err_name; name.classList.add('error'); valid = false; }
  const mobileVal = mobile.value.trim().replace(/\s+/g, '');
  if (!/^[6-9]\d{9}$/.test(mobileVal)) { document.getElementById('mobileError').textContent = t.err_mobile; mobile.classList.add('error'); valid = false; }
  if (!society.value.trim()) { document.getElementById('societyError').textContent = t.err_society; society.classList.add('error'); valid = false; }
  if (!location.value.trim()) { document.getElementById('locationError').textContent = t.err_location; location.classList.add('error'); valid = false; }
  if (!service.value) { document.getElementById('serviceError').textContent = t.err_service; service.classList.add('error'); valid = false; }
  return valid;
}

