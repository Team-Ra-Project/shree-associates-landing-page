function validateForm() {
  const t = translations[currentLang];
  let valid = true;

  const name = document.getElementById('fullName');
  const mobile = document.getElementById('mobile');
  const email = document.getElementById('email');
  const society = document.getElementById('societyName');
  const location = document.getElementById('location');
  const service = document.getElementById('service');

  // Clear previous errors
  document.querySelectorAll('.error-msg').forEach(e => e.textContent = '');
  document.querySelectorAll('.form-group input, .form-group select').forEach(el => el.classList.remove('error'));

  if (!name.value.trim()) {
    document.getElementById('nameError').textContent = t.err_name;
    name.classList.add('error');
    valid = false;
  }

  const mobileVal = mobile.value.trim().replace(/\s+/g, '');
  if (!/^[6-9]\d{9}$/.test(mobileVal)) {
    document.getElementById('mobileError').textContent = t.err_mobile;
    mobile.classList.add('error');
    valid = false;
  }

  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.value.trim())) {
    document.getElementById('emailError').textContent = t.err_email;
    email.classList.add('error');
    valid = false;
  }

  if (!society.value.trim()) {
    document.getElementById('societyError').textContent = t.err_society;
    society.classList.add('error');
    valid = false;
  }

  if (!location.value.trim()) {
    document.getElementById('locationError').textContent = t.err_location;
    location.classList.add('error');
    valid = false;
  }

  if (!service.value) {
    document.getElementById('serviceError').textContent = t.err_service;
    service.classList.add('error');
    valid = false;
  }

  return valid;
}

function handleFormSubmit(e) {
  e.preventDefault();
  if (!validateForm()) return;

  const formData = {
    fullName: document.getElementById('fullName').value.trim(),
    mobile: document.getElementById('mobile').value.trim().replace(/\s+/g, ''),
    email: document.getElementById('email').value.trim(),
    societyName: document.getElementById('societyName').value.trim(),
    location: document.getElementById('location').value.trim(),
    service: document.getElementById('service').value,
    message: document.getElementById('message').value.trim(),
    language: currentLang,
    timestamp: new Date().toISOString()
  };

  const submitBtn = e.target.querySelector('[type="submit"]');
  submitBtn.disabled = true;

  submitEnquiryToBackend(formData).then(() => {
    document.getElementById('formSuccess').hidden = false;
    e.target.reset();
    submitBtn.disabled = false;
    setTimeout(() => {
      document.getElementById('formSuccess').hidden = true;
    }, 6000);
  }).catch(() => {
    submitBtn.disabled = false;
  });
}

/* ===== FAQ ACCORDION ===== */
function initFAQ() {
  document.querySelectorAll('.faq-q').forEach(btn => {
    btn.addEventListener('click', () => {
      const item = btn.parentElement;
      const isOpen = item.classList.contains('open');
      document.querySelectorAll('.faq-item').forEach(i => {
        i.classList.remove('open');
        i.querySelector('.faq-q').setAttribute('aria-expanded', 'false');
      });
      if (!isOpen) {
        item.classList.add('open');
        btn.setAttribute('aria-expanded', 'true');
      }
    });
  });
}

/* ===== MOBILE MENU ===== */
function initMobileMenu() {
  const hamburger = document.getElementById('hamburger');
  const mobileMenu = document.getElementById('mobileMenu');
  hamburger.addEventListener('click', () => {
    hamburger.classList.toggle('open');
    mobileMenu.classList.toggle('open');
  });
  mobileMenu.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      hamburger.classList.remove('open');
      mobileMenu.classList.remove('open');
    });
  });
}

/* ===== SCROLL ANIMATIONS ===== */
function initScrollAnimations() {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

  document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));
}

/* ===== NAVBAR SCROLL ===== */
function initNavbar() {
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 20);
  });
}

